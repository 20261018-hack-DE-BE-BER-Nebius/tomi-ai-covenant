import { spawn } from "node:child_process";
import { mkdir, writeFile, chmod } from "node:fs/promises";
import { existsSync } from "node:fs";
import { resolve } from "node:path";
import { loadConfig } from "../dist/config.js";
import { openclawConfig, childEnvironment } from "../dist/openclaw-config.js";
if (existsSync(".env")) process.loadEnvFile();
const settings = loadConfig();
const root = resolve("runtime");
const workspace = resolve("workspace");
await mkdir(root, { recursive: true, mode: 0o700 });
await chmod(root, 0o700);
await mkdir(workspace, { recursive: true, mode: 0o700 });
const configPath = resolve(root, "openclaw.json");
await writeFile(configPath, JSON.stringify(openclawConfig(settings, workspace, resolve("plugins/evidence")), null, 2), { mode: 0o600 });
await chmod(configPath, 0o600);
const command = process.argv.includes("--validate") ? ["config", "validate"] : ["gateway", "run"];
const child = spawn(process.execPath, ["node_modules/openclaw/openclaw.mjs", ...command], { env: childEnvironment(settings, process.env, configPath, root), stdio: "inherit" });
for (const signal of ["SIGTERM", "SIGINT"]) process.on(signal, () => child.kill(signal));
child.on("error", () => process.exit(1));
child.on("exit", code => process.exit(code ?? 1));
